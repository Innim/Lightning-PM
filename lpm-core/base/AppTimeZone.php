<?php
/**
 * Часовой пояс приложения.
 *
 * Инвариант: зона PHP и зона соединения с БД — всегда одна и та же. Момент
 * ходит между приложением и базой строкой без указания зоны, поэтому любое
 * расхождение сдвигает каждую дату на разницу между зонами, причём молча:
 * значение остаётся правдоподобным.
 *
 * Поэтому зона соединения не настраивается отдельно, а вычисляется из
 * действующей зоны PHP — см. mysqlOffset(). Единственное место, где зона
 * задаётся, — `date_default_timezone_set()` в `init.inc.php`.
 *
 * Переходный период: колонки `datetime` хранят не момент, а показание часов,
 * поэтому рядом с каждой такой колонкой заведён близнец `<имя>Utc` типа
 * `timestamp`. Чтение пока идёт из старой колонки, а близнец накапливается
 * под будущее переключение — значит запись обязана заполнять обе колонки
 * одним и тем же значением. Полный список пар — в миграции
 * `..._dates_absolute_timestamp_columns.php`.
 */
class AppTimeZone
{
    /**
     * Смещение зоны приложения в формате, который MySQL принимает
     * в `SET time_zone` — например `+03:00`.
     *
     * Берётся числовое смещение, а не имя зоны: имена MySQL понимает только
     * с загруженными таблицами часовых поясов (`mysql.time_zone*`), которых
     * на установке может не быть.
     *
     * Ограничение: если зона приложения переходит на летнее время, смещение
     * берётся по текущему моменту, и значения по другую сторону перехода
     * запишутся со сдвигом в час. Зона приложения перехода не имеет.
     *
     * @return string
     */
    public static function mysqlOffset()
    {
        return date('P');
    }

    /**
     * Объявляет соединению зону приложения.
     *
     * Без этого соединение работает в зоне сервера БД, и она в общем случае
     * не совпадает с зоной приложения.
     *
     * @param  DBConnect $db Соединение с БД.
     * @return void
     */
    public static function applyToConnection($db)
    {
        self::checkTimeAdjust();

        // Смещение состоит только из цифр и знака, подстановка безопасна.
        $db->query("SET time_zone = '" . self::mysqlOffset() . "'");
    }

    /**
     * Предупреждает, если инвариант нарушен настройкой TIMEADJUST.
     *
     * `TIMEADJUST` сдвигает время, которое возвращает `DateTimeUtils`, не
     * меняя при этом зону PHP. Зона соединения считается по зоне PHP и такого
     * сдвига не знает, поэтому приложение начинает писать в БД одно время,
     * а читать другое. Правильный способ сместить время — задать зону
     * приложения, а не TIMEADJUST.
     *
     * @return void
     */
    private static function checkTimeAdjust()
    {
        if (defined('TIMEADJUST') && TIMEADJUST != 0) {
            trigger_error(
                'TIMEADJUST = ' . TIMEADJUST . ': сдвиг времени настройкой TIMEADJUST не '
                . 'учитывается зоной соединения с БД, даты будут записаны со смещением. '
                . 'Задайте часовой пояс приложения вместо TIMEADJUST.',
                E_USER_WARNING
            );
        }
    }
}
