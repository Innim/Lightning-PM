 * которого приложение работоспособно. На установке, существовавшей до
 * перехода на миграции, схема уже создана дампом — там миграция при первом
 * запуске отмечается применённой без выполнения (см. DbMigrator::BASELINE).
 *
 * Отката нет намеренно: он означал бы удаление всех данных.
 */
return new class extends DbMigration {
    public function up()
    {
        // Страховка на случай, если базис не сработал: миграция создаёт схему
        // только на пустой базе и никогда не трогает существующую.
        if ($this->tableExists($this->t(LPMTables::ISSUES))) {
            throw new DbMigrationException(
                'база уже содержит таблицы приложения — схему нельзя создавать'
                . ' поверх существующей установки; отметьте миграцию'
                . ' применённой командой baseline'
            );
        }

        $this->execFile('00000000000000_initial_schema.sql');
    }
