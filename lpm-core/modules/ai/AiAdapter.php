<?php
/**
 * Общий интерфейс адаптера для работы с ИИ-моделями через API.
 *
 * Реализация инкапсулирует особенности конкретного провайдера
 * (формат запроса и ответа, авторизация, адрес API), предоставляя
 * приложению единый способ обращения к модели.
 */
interface AiAdapter
{
    /**
     * Идентификатор провайдера (одна из констант AiIntegration::PROVIDER_*).
     * @return string
     */
    public function getProviderName();

    /**
     * Модель, которая используется по умолчанию.
     * @return string
     */
    public function getModel();

    /**
     * Настроен ли адаптер, т.е. заданы ли параметры доступа к API.
     * Пока адаптер не настроен, запросы к модели выполнять нельзя.
     * @return bool
     */
    public function isConfigured();

    /**
     * Выполняет запрос к модели и возвращает её ответ.
     *
     * @param AiRequest $request Запрос к модели.
     * @return AiResponse Ответ модели.
     * @throws AiException Если адаптер не настроен, запрос некорректен,
     * произошла ошибка обращения к API или ответ не удалось разобрать.
     */
    public function generate(AiRequest $request);
}
