<?php
/**
 * Обработка имени загруженного файла.
 *
 * Имя приходит от пользователя, поэтому обрабатывается по одним правилам
 * для файла и для картинки: иначе у двух видов вложений разойдётся не только
 * имя, но и защита.
 *
 * Различает два имени, которые раньше были одним. Отображаемое имя - то,
 * под которым файл загрузили: оно хранится, показывается и подставляется
 * в имя скачиваемого файла, поэтому специальные символы в нём сохраняются.
 * Имя для файловой системы и для заголовка ответа - урезанное до безопасного
 * набора символов; путём на диске отображаемое имя не становится никогда,
 * файл лежит под сгенерированным именем.
 */
class FileNameHelper
{
    /**
     * Приводит имя только что загруженного файла к виду, в котором оно
     * хранится и показывается пользователю.
     * @param  string $name     Имя из `$_FILES`.
     * @param  string $fallback Что вернуть, если от имени ничего не осталось
     *   или оно не разбирается как UTF-8.
     * @return string Валидный UTF-8 либо $fallback.
     */
    public static function displayNameFromUpload($name, $fallback = '')
    {
        return self::normalizeDisplayName(self::decodeUploadedName($name), $fallback);
    }

    /**
     * Приводит отображаемое имя к виду, пригодному для показа и для подстановки
     * в имя скачиваемого файла: вырезаются управляющие символы, длина
     * ограничивается {@see FileNameHelper::MAX_LENGTH} символами.
     *
     * Остальные символы сохраняются, в том числе кавычки и угловые скобки:
     * пользователь должен увидеть то имя, под которым загрузил файл.
     * Экранирование при выводе остаётся за вызывающим кодом - в HTML через
     * {@see HTMLHelper::escape()}, в заголовок ответа через
     * {@see FileNameHelper::asciiFileName()} и `rawurlencode()`.
     *
     * Нормализация идемпотентна: на уже нормализованном имени она ничего
     * не меняет, поэтому её можно повторить над сохранённым значением.
     * @param  string $name
     * @param  string $fallback Что вернуть, если от имени ничего не осталось
     *   или оно не разбирается как UTF-8.
     * @return string Валидный UTF-8 либо $fallback.
     */
    public static function normalizeDisplayName($name, $fallback = '')
    {
        // Управляющие символы: в имени они не несут смысла, а перевод строки
        // в заголовке ответа позволил бы подставить свои заголовки.
        // preg_replace() возвращает null, если в имени невалидный UTF-8 -
        // такое имя считаем неизвестным
        $name = preg_replace('/[\x00-\x1F\x7F]/u', '', (string)$name);
        if (null === $name) {
            return $fallback;
        }

        $name = trim($name);

        return '' === $name ? $fallback : mb_substr($name, 0, self::MAX_LENGTH);
    }

    /**
     * Имя для параметра `filename` заголовка `Content-Disposition` - того,
     * который читают клиенты, не понимающие `filename*`.
     *
     * По RFC 6266 в этом параметре допустим только ASCII, а кавычка и обратная
     * косая закрыли бы строку раньше времени. Поэтому всё, что вне печатного
     * ASCII, и символы, недопустимые в имени файла, заменяются на `_`;
     * настоящее имя клиент получает из `filename*`.
     * @param  string $name
     * @param  string $fallback Что вернуть, если от имени ничего не осталось.
     * @return string Печатный ASCII без кавычек и обратных косых.
     */
    public static function asciiFileName($name, $fallback = self::DEFAULT_NAME)
    {
        // Байтовый режим (без модификатора `u`): имя может прийти
        // и с невалидным UTF-8, а каждый негодный байт всё равно заменяется
        $name = preg_replace('/[^\x20-\x7E]+|["\\\\\/:*?<>|]+/', '_', (string)$name);
        $name = trim($name);

        return '' === $name ? $fallback : substr($name, 0, self::MAX_LENGTH);
    }

    /**
     * Снимает кодирование, которым браузер закрыл имя в параметре `filename`
     * multipart-запроса.
     *
     * По стандарту HTML браузер percent-кодирует там ровно три символа - `"`,
     * CR и LF, - а PHP это кодирование не снимает: имя с кавычкой приходит
     * в `$_FILES` с `%22`. Разбираем только эти три последовательности;
     * percent-декодирование целиком испортило бы имя, в котором пользователь
     * сам написал, например, `%20`.
     *
     * Однозначно обратимым это кодирование не является: имя `a%22b` браузер
     * передаёт как есть, и от закодированной кавычки его не отличить - такое
     * имя станет `a"b`. Кавычка в имени встречается несравнимо чаще, чем
     * записанная вручную escape-последовательность, поэтому разбор выгоднее
     * его отсутствия.
     * @param  string $name Имя из `$_FILES`.
     * @return string
     */
    private static function decodeUploadedName($name)
    {
        // Регистр не фиксируем: стандарт предписывает верхний, но браузер,
        // который отступит от него, иначе оставил бы `%22` видимым в имени
        return str_ireplace(['%0A', '%0D', '%22'], ["\n", "\r", '"'], (string)$name);
    }

    /**
     * Максимальная длина имени, символов: столько вмещают колонки,
     * в которых имя хранится.
     */
    const MAX_LENGTH = 255;

    /**
     * Имя, под которым сохраняется файл, от имени которого ничего не осталось.
     */
    public const DEFAULT_NAME = 'file';
}
