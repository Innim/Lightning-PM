<?php
/**
 * Приведение имени загруженного файла к безопасному виду.
 *
 * Имя приходит от пользователя, поэтому чистится по одним правилам для файла
 * и для картинки: иначе у двух видов вложений разойдётся не только имя,
 * но и защита.
 */
class FileNameHelper
{
    /**
     * Приводит имя файла к виду, пригодному для показа пользователю и для
     * подстановки в имя скачиваемого файла: разделители пути и символы,
     * недопустимые в имени файла, заменяются на `_`, управляющие символы
     * вырезаются, длина ограничивается {@see FileNameHelper::MAX_LENGTH}
     * символами.
     *
     * Имя не влияет на путь к файлу на диске - на диске файл лежит под
     * сгенерированным именем. Экранирование при выводе в HTML и в заголовки
     * ответа остаётся за вызывающим кодом.
     *
     * Очистка идемпотентна: на уже очищенном имени она ничего не меняет,
     * поэтому её можно повторить над сохранённым значением.
     * @param  string $name
     * @param  string $fallback Что вернуть, если чистить нечего: имя пустое
     *   или не разбирается как UTF-8.
     * @return string Валидный UTF-8 либо $fallback.
     */
    public static function sanitize($name, $fallback = '')
    {
        $name = trim((string)$name);
        // Разделители пути и символы, недопустимые в имени файла в Windows
        $name = preg_replace('/[\\\\\/\:\*\?"<>\|]+/', '_', $name);
        // Управляющие символы: в имени они не несут смысла, а перевод строки
        // в заголовке ответа позволил бы подставить свои заголовки.
        // preg_replace() возвращает null, если в имени невалидный UTF-8 -
        // такое имя считаем неизвестным
        $name = preg_replace('/[\x00-\x1F\x7F]/u', '', (string)$name);

        if (null === $name || '' === $name) {
            return $fallback;
        }

        return mb_substr($name, 0, self::MAX_LENGTH);
    }

    /**
     * Максимальная длина имени, символов: столько вмещают колонки,
     * в которых имя хранится.
     */
    const MAX_LENGTH = 255;
}
