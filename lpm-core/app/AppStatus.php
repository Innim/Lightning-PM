<?php
/**
 * Состояние приложение.
 */
class AppStatus
{
    /**
     * Определяет, включен ли кэш.
     */
    public $cacheEnabled;

    /**
     * Адрес, с которого запрос пришёл к веб-серверу. За обратным прокси это
     * адрес прокси, общий для всех пользователей.
     * @var string
     */
    public $remoteAddr = '';

    /**
     * Достоверно установленный адрес пользователя.
     * @var string Пустая строка, если установить его нельзя.
     */
    public $clientIp = '';

    /**
     * Заданы ли адреса доверенных прокси.
     * @var bool
     */
    public $trustedProxiesConfigured = false;

    /**
     * Применяется ли ограничение числа попыток входа с одного адреса.
     * Работает только там, где адрес пользователя известен достоверно.
     * @var bool
     */
    public $loginIpLimitEnabled = false;
}
