<?php
/**
 * Уточнение статуса задачи: на каком этапе она внутри своего статуса.
 *
 * Подстатус нигде не хранится - он вычисляется по данным, которые и так
 * приезжают вместе с задачей: для «В работе» это состояние стикера
 * на Scrum доске, для «Ожидает проверки» - отметка о том, что задачу
 * взяли на проверку или что она уже прошла тестирование.
 * @see Issue::getSubstatus()
 */
class IssueSubstatus
{
    /**
     * Подстатуса нет: у статуса задачи нет уточнения либо его не из чего вывести
     * (задача в работе в проекте без Scrum).
     */
    const NONE = 0;

    /**
     * Задача не на доске - лежит в общем бэклоге проекта.
     */
    const BACKLOG = 1;

    /**
     * Задача на доске в колонке «К выполнению».
     */
    const TODO = 2;

    /**
     * Задача на доске в работе.
     */
    const IN_PROGRESS = 3;

    /**
     * Задача в тесте, по ней стоит отметка о прохождении тестирования.
     */
    const PASS_TEST = 4;

    /**
     * Задача в тесте и кто-то уже взял её на проверку.
     */
    const TAKEN_FOR_TESTING = 5;

    /**
     * Отображаемое название подстатуса.
     * @param  int $substatus Подстатус.
     * @return string Название. Пустая строка, если подстатуса нет.
     */
    public static function getName($substatus)
    {
        switch ((int)$substatus) {
            case self::BACKLOG: return 'Бэклог';
            case self::TODO: return 'К выполнению';
            case self::IN_PROGRESS: return 'В работе';
            case self::PASS_TEST: return 'Прошла тестирование';
            case self::TAKEN_FOR_TESTING: return 'Взята в тестирование';
            default: return '';
        }
    }
}
